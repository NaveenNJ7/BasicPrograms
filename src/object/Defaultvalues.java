package object;

public class Defaultvalues {
	
	 int a;
	 double b;
	 char c;
	 String d;
	 public static void main(String[] args) {
		
		 
		 
		 Defaultvalues v = new Defaultvalues();
		 
		 System.out.println(v.a); // 0
		 System.out.println(v.b); //0.0
		 System.out.println(v.c); // empty space
		 System.out.println(v.d); // null
	}

}
