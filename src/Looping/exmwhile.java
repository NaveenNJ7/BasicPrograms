package Looping;

public class exmwhile {
	
	public static void main(String[] array)
	{
		int n = 1;
		while(n<=5)
		{
			System.out.println(n);
			n=n+1; // n++
		}
		System.out.println("----------");
		int m =2;
		System.out.println("Even numbers");
		while(m<=10)
		{
			System.out.println(m);
			m+=2;
		}
		
		int p = 3;
		System.out.println("Multiplese of 3");
		while(p<=30)
		{
			System.out.println(p);
			p+=3;
		}
	}

}
