package Looping;

public class exmforloop {
	
	public static void main(String[] args)
	{
		System.out.println("Number between 1 to 5");
		
		for(int i=1; i<=5; i++)
		{
			System.out.println(i);
		}
		
		System.out.println("Even numbers between 1 to 10");
		
		for(int i=2; i<=10; i+=2) // i=i+2
		{
			System.out.println(i);
		}
		
		System.out.println("Odd numbers between 1 to 10");
		
		for(int i=1; i<=10; i+=2)
		{
			System.out.println(i);
		}
		
		System.out.println("Numbers between 11 to 15");
		
		for(int i=11; i<=15; i++)
		{
			System.out.println(i);
		} 
		
		
	}

}
